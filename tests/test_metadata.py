        "START_OF_HEADER",
        "FLAVOR:Griffin",
        "GENERATOR.NAME:Cura_SteamEngine",
        "GENERATOR.VERSION:5.7.1",
        "TARGET_MACHINE.NAME:Ultimaker S5",
