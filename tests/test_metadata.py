from __future__ import annotations

import pytest

from gcode_insight.metadata import MetadataCollector, SlicerMetadata, parse_duration


def collect(*comments: str) -> SlicerMetadata:
    collector = MetadataCollector()
    for comment in comments:
        collector.feed(comment)
    return collector.metadata


@pytest.mark.parametrize(
    ("text", "seconds"),
    [
        ("17m 22s", 1042.0),
        ("1h 2m 3s", 3723.0),
        ("2d 0h 0m 30s", 172830.0),
        ("45s", 45.0),
        ("1h2m", 3720.0),
    ],
)
def test_parse_duration(text: str, seconds: float) -> None:
    assert parse_duration(text) == seconds


def test_parse_duration_without_units() -> None:
    assert parse_duration("soon") is None


def test_bambu_header_and_config() -> None:
    meta = collect(
        "HEADER_BLOCK_START",
        "BambuStudio 01.09.07.52",
        "model printing time: 11m 8s; total estimated time: 17m 22s",
        "total layer number: 50",
        "total filament length [mm] : 1234.56,78.90",
        "total filament volume [cm^3] : 2969.42,189.78",
        "total filament weight [g] : 3.68,0.24",
        "filament_density: 1.24,1.27",
        "filament_diameter: 1.75,1.75",
        "HEADER_BLOCK_END",
        "CONFIG_BLOCK_START",
        "filament_type = PLA;PETG",
        "initial_layer_print_height = 0.2",
        "layer_height = 0.16",
        "nozzle_diameter = 0.4",
    )
    assert meta.slicer == "BambuStudio"
    assert meta.slicer_version == "01.09.07.52"
    assert meta.model_time_s == 668.0
    assert meta.estimated_time_s == 1042.0
    assert meta.total_layers == 50
    assert meta.filament_used_mm == [1234.56, 78.90]
    assert meta.filament_used_g == [3.68, 0.24]
    assert meta.filament_density == [1.24, 1.27]
    assert meta.filament_diameter == [1.75, 1.75]
    assert meta.filament_type == ["PLA", "PETG"]
    assert meta.first_layer_height == 0.2
    assert meta.layer_height == 0.16
    assert meta.nozzle_diameter == 0.4
    assert not meta.is_empty


def test_prusaslicer_banner_and_footer() -> None:
    meta = collect(
        "generated by PrusaSlicer 2.7.1+win64 on 2024-01-15 at 10:22:33 UTC",
        "filament used [mm] = 4321.09",
        "filament used [cm3] = 10.39",
        "filament used [g] = 13.20",
        "total filament used [g] = 13.20",
        "estimated printing time (normal mode) = 1h 2m 3s",
        "estimated printing time (silent mode) = 1h 5m 0s",
        "filament_type = PETG",
        "first_layer_height = 50%",
        "layer_height = 0.2",
        "nozzle_diameter = 0.4,0.4",
    )
    assert (meta.slicer, meta.slicer_version) == ("PrusaSlicer", "2.7.1+win64")
    assert meta.filament_used_mm == [4321.09]
    assert meta.filament_used_cm3 == [10.39]
    assert meta.filament_used_g == [13.20]
    assert meta.estimated_time_s == 3723.0
    assert meta.model_time_s is None
    assert meta.filament_type == ["PETG"]
    assert meta.first_layer_height is None  # percentages are not resolved
    assert meta.layer_height == 0.2
    assert meta.nozzle_diameter == 0.4


